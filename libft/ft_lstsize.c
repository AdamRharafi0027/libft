#include "libft.h"

unsigned int	ft_lstsize(t_list *lst)
{
	size_t	count;
	t_list	*current;

	count = 0;
	current = lst;
	while (current != NULL)
	{
		count++;
		current = current->next;
	}
	return (count);
}
